//! The cell rules of VEP's tab and CSQ output, end to end (issue #139).
//!
//! What the reporter's downstream code selects on is the tab file, and some of
//! its cells did not follow VEP:
//!
//! - `Uploaded_variation` of a record without an ID was `chr10:10401-10405_ACCCT/-`;
//!   VEP's is the line it was given, `chr10_10400_AACCCT/A`.
//! - an absent cDNA, CDS or protein position was an empty string; VEP writes `-`
//!   for every value it does not have.
//! - an intergenic row said `Feature_type` `Transcript` and `STRAND` `1`; it has
//!   no feature, so VEP leaves both `-` (and empty in a VCF CSQ entry).
//! - an insertion's `Location` ran high to low.
//!
//! The expectations are Ensembl VEP 116.3's own output for this input, run in
//! Docker: `fixtures/vep_tab_cells/golden.tab`, regenerated by `regen.sh` there.
//! `the_default_tab_file_is_cell_for_cell_the_one_vep_writes` holds the whole
//! default tab file to it; the other tests name the rule each cell is an example
//! of, so that a failure says which.

use std::collections::HashMap;
use std::path::{Path, PathBuf};

use fastvep_cli::pipeline::{run_annotate, AnnotateConfig, PickFlags};
use tempfile::TempDir;

/// A file of `fixtures/vep_tab_cells`.
fn fixture(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("fixtures/vep_tab_cells")
        .join(name)
}

/// The fixture's VCF annotated against its GFF3, in `format`.
fn run(dir: &Path, format: &str) -> String {
    let out = dir.join(format!("out.{format}"));
    run_annotate(AnnotateConfig {
        input: fixture("in.vcf").to_string_lossy().into(),
        output: out.to_string_lossy().into(),
        gff3: vec![fixture("genes.gff3").to_string_lossy().into()],
        fasta: None,
        output_format: format.into(),
        pick: PickFlags::default(),
        hgvs: false,
        distance: 5000,
        cache_dir: None,
        transcript_cache: None,
        sa_dir: None,
        sa_only: false,
        acmg: false,
        acmg_config: None,
        pick_order: None,
        functional_evidence: None,
        proband: None,
        mother: None,
        father: None,
        gene_list: None,
        explicit_alleles: false,
        qc_rules: None,
        show_progress: false,
        columns: Default::default(),
    })
    .expect("annotation should succeed");
    std::fs::read_to_string(&out).unwrap()
}

/// Data rows of the tab file, each as column name to cell.
fn tab_rows(tab: &str) -> Vec<HashMap<String, String>> {
    let header: Vec<&str> = tab
        .lines()
        .find(|l| l.starts_with("#Uploaded_variation"))
        .unwrap_or_else(|| panic!("no column header in:\n{tab}"))
        .trim_start_matches('#')
        .split('\t')
        .collect();
    tab.lines()
        .filter(|l| !l.starts_with('#'))
        .map(|row| {
            let cells: Vec<&str> = row.split('\t').collect();
            assert_eq!(cells.len(), header.len(), "ragged row: {row:?}");
            header
                .iter()
                .zip(cells)
                .map(|(h, c)| (h.to_string(), c.to_string()))
                .collect()
        })
        .collect()
}

fn find<'a>(
    rows: &'a [HashMap<String, String>],
    uploaded: &str,
    allele: &str,
) -> &'a HashMap<String, String> {
    rows.iter()
        .find(|r| r["Uploaded_variation"] == uploaded && r["Allele"] == allele)
        .unwrap_or_else(|| panic!("no row for {uploaded} {allele} in {rows:#?}"))
}

/// The whole default tab file, cell for cell, against what VEP 116.3 wrote for
/// the same input. The other tests in this file are examples of single rules;
/// this one is the file the reporter's code reads.
#[test]
fn the_default_tab_file_is_cell_for_cell_the_one_vep_writes() {
    let dir = TempDir::new().unwrap();
    let ours = run(dir.path(), "tab");
    let theirs = std::fs::read_to_string(fixture("golden.tab")).unwrap();
    let table = |text: &str| -> Vec<Vec<String>> {
        text.lines()
            .filter(|l| !l.starts_with("##"))
            .map(|l| {
                l.trim_start_matches('#')
                    .split('\t')
                    .map(String::from)
                    .collect()
            })
            .collect()
    };
    let (ours, theirs) = (table(&ours), table(&theirs));
    assert_eq!(ours[0], theirs[0], "the column header");
    assert_eq!(ours.len(), theirs.len(), "rows");
    for (row, want) in ours.iter().zip(&theirs).skip(1) {
        assert_eq!(row, want, "the row of {}", want[0]);
    }
}

#[test]
fn uploaded_variation_is_vep_s_name() {
    let dir = TempDir::new().unwrap();
    let tab = run(dir.path(), "tab");
    let rows = tab_rows(&tab);

    let mut names: Vec<(String, String)> = rows
        .iter()
        .map(|r| (r["Uploaded_variation"].clone(), r["Allele"].clone()))
        .collect();
    names.sort_unstable();
    let mut want: Vec<(&str, &str)> = vec![
        ("chr10_10414_C/A", "A"),
        ("rs100", "T"),
        // the first of two IDs
        ("rs1", "T"),
        // the line as it was written, whatever it trims to
        ("chr10_11900_GA/G", "-"),
        // a multi-allelic record keeps its whole allele string, on both rows
        ("chr10_11950_C/A/G", "A"),
        ("chr10_11950_C/A/G", "G"),
        // the inserted bases sit between 11960 and 11961
        ("chr10_11960_T/TTT", "TT"),
        ("chrM_100_A/G", "G"),
    ];
    want.sort_unstable();
    let want: Vec<(String, String)> = want
        .into_iter()
        .map(|(a, b)| (a.to_string(), b.to_string()))
        .collect();
    assert_eq!(names, want, "\n{tab}");
}

/// VEP writes `-` for every value it does not have. A data row never has an
/// empty cell.
#[test]
fn no_data_cell_of_the_tab_file_is_empty() {
    let dir = TempDir::new().unwrap();
    let tab = run(dir.path(), "tab");
    for row in tab.lines().filter(|l| !l.starts_with('#')) {
        for (i, cell) in row.split('\t').enumerate() {
            assert!(!cell.is_empty(), "empty cell {i} in {row:?}");
        }
    }
}

/// VEP's `format_coords` puts the lower coordinate first, so an insertion, which
/// has its end below its start, is `chr10:11960-11961`. `Location` is what a
/// reader joins the rows back to the input on.
#[test]
fn an_insertion_location_runs_low_to_high() {
    let dir = TempDir::new().unwrap();
    let rows = tab_rows(&run(dir.path(), "tab"));
    let insertion = find(&rows, "chr10_11960_T/TTT", "TT");
    assert_eq!(insertion["Location"], "chr10:11960-11961");
    // a deletion and an SNV are as they were
    assert_eq!(
        find(&rows, "chr10_11900_GA/G", "-")["Location"],
        "chr10:11901"
    );
    assert_eq!(
        find(&rows, "chr10_10414_C/A", "A")["Location"],
        "chr10:10414"
    );
}

#[test]
fn positions_are_dashes_where_there_is_none_and_numbers_where_there_is() {
    let dir = TempDir::new().unwrap();
    let rows = tab_rows(&run(dir.path(), "tab"));

    // upstream of the gene: no position in the transcript at all
    let upstream = find(&rows, "chr10_10414_C/A", "A");
    assert_eq!(upstream["Consequence"], "upstream_gene_variant");
    for col in ["cDNA_position", "CDS_position", "Protein_position"] {
        assert_eq!(upstream[col], "-", "{col} of an upstream row");
    }
    assert_eq!(upstream["DISTANCE"], "1316");

    // inside the first exon, base 71 of the transcript; it is not coding
    let exonic = find(&rows, "rs100", "T");
    assert_eq!(exonic["cDNA_position"], "71");
    assert_eq!(exonic["CDS_position"], "-");
    assert_eq!(exonic["Protein_position"], "-");
}

/// An intergenic row has no feature. VEP never sets `Feature_type`, `STRAND`,
/// `FLAGS` or `DISTANCE` for it, though it does set `IMPACT`.
#[test]
fn an_intergenic_row_has_no_feature_cells() {
    let dir = TempDir::new().unwrap();
    let rows = tab_rows(&run(dir.path(), "tab"));
    let row = find(&rows, "chrM_100_A/G", "G");

    assert_eq!(row["Consequence"], "intergenic_variant");
    assert_eq!(row["IMPACT"], "MODIFIER");
    for col in [
        "Gene",
        "Feature",
        "Feature_type",
        "DISTANCE",
        "STRAND",
        "FLAGS",
    ] {
        assert_eq!(row[col], "-", "{col} of an intergenic row");
    }

    // a transcript row keeps its feature cells
    let upstream = find(&rows, "chr10_10414_C/A", "A");
    assert_eq!(upstream["Feature_type"], "Transcript");
    assert_eq!(upstream["Feature"], "ENST_X");
    assert_eq!(upstream["Gene"], "ENSG_X");
    assert_eq!(upstream["STRAND"], "1");
}

/// The VCF output has the same rule. A `Feature_type` of `Transcript` on an
/// intergenic entry made `Feature_type is Transcript` select it.
#[test]
fn an_intergenic_csq_entry_has_no_feature_fields() {
    let dir = TempDir::new().unwrap();
    let vcf = run(dir.path(), "vcf");
    let header = vcf
        .lines()
        .find(|l| l.starts_with("##INFO=<ID=CSQ"))
        .expect("a CSQ header");
    let fields: Vec<&str> = header
        .split("Format: ")
        .nth(1)
        .and_then(|rest| rest.split("\">").next())
        .expect("a declared format")
        .split('|')
        .collect();

    let entry_of = |chrom: &str| -> HashMap<&str, String> {
        let record = vcf
            .lines()
            .find(|l| l.starts_with(&format!("{chrom}\t")))
            .unwrap_or_else(|| panic!("no {chrom} record in:\n{vcf}"));
        let info = record.split('\t').nth(7).unwrap();
        let csq = info
            .split(';')
            .find_map(|kv| kv.strip_prefix("CSQ="))
            .expect("a CSQ value");
        let entry = csq.split(',').next().unwrap();
        fields
            .iter()
            .copied()
            .zip(entry.split('|').map(String::from))
            .collect()
    };

    let intergenic = entry_of("chrM");
    assert_eq!(intergenic["Consequence"], "intergenic_variant");
    assert_eq!(intergenic["IMPACT"], "MODIFIER");
    for name in [
        "Gene",
        "Feature_type",
        "Feature",
        "BIOTYPE",
        "STRAND",
        "DISTANCE",
    ] {
        assert_eq!(intergenic[name], "", "{name} of an intergenic CSQ entry");
    }

    let upstream = entry_of("chr10");
    assert_eq!(upstream["Feature_type"], "Transcript");
    assert_eq!(upstream["Feature"], "ENST_X");
    assert_eq!(upstream["STRAND"], "1");
}
